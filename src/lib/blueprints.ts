export type EnvEntry = { key: string; value: string; quote: string; line: number; error?: string };
export function parseEnv(src: string): EnvEntry[] {
  const out: EnvEntry[] = [];
  src.split("\n").forEach((raw, idx) => {
    const line = idx + 1;
    const trimmed = raw.trim();
    if (!trimmed || trimmed.startsWith("#")) return;
    const noExport = trimmed.replace(/^export\s+/, "");
    const m = noExport.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) { out.push({ key: "", value: raw, quote: "", line, error: `Line ${line}: expected KEY=value.` }); return; }
    let v = m[2].trim();
    let quote = "";
    if ((v.startsWith('"') && v.endsWith('"') && v.length >= 2) || (v.startsWith("'") && v.endsWith("'") && v.length >= 2)) { quote = v[0]; v = v.slice(1, -1); }
    else v = v.split(/\s+#/)[0].trim();
    if (!/^[A-Z_][A-Z0-9_]*$/i.test(m[1])) { /* allow lowercase with warning */ }
    out.push({ key: m[1], value: v, quote, line });
  });
  return out;
}
export function envToJson(src: string): string {
  const o: Record<string, string> = {};
  parseEnv(src).filter((e) => !e.error).forEach((e) => { o[e.key] = e.value; });
  return JSON.stringify(o, null, 2);
}
export function jsonToEnv(input: string): string {
  const v = JSON.parse(input);
  if (!v || typeof v !== "object" || Array.isArray(v)) throw new Error("JSON → .env needs a flat object of string values.");
  return Object.entries(v as Record<string, unknown>).map(([k, val]) => {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) throw new Error(`Invalid env key "${k}": use A–Z, 0–9 and underscore.`);
    const s = String(val ?? "");
    return /[\s#"']/.test(s) ? `${k}="${s.replace(/"/g, '\\"')}"` : `${k}=${s}`;
  }).join("\n") + "\n";
}

