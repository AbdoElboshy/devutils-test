export function tfVariables(names: string): string {
  return names.split("\n").map((l) => l.trim()).filter(Boolean).map((l) => {
    const [name, def] = l.split("=").map((s) => s.trim());
    return `variable "${name}" {\n  description = "${name}"\n  type        = string${def ? `\n  default     = ${JSON.stringify(def)}` : ""}\n}`;
  }).join("\n\n");
}
export function tfOutputs(names: string): string {
  return names.split("\n").map((l) => l.trim()).filter(Boolean).map((n) => `output "${n}" {\n  description = "${n}"\n  value       = ${n.includes(".") ? n : `aws_example.${n}.id`}\n}`).join("\n\n");
}
export function tfFormat(hcl: string): string {
  // deterministic light formatter: 2-space indent by braces
  const lines = hcl.split("\n");
  let depth = 0;
  return lines.map((raw) => {
    const l = raw.trim();
    if (!l) return "";
    if (/^[}\])]/.test(l)) depth = Math.max(0, depth - 1);
    const out = "  ".repeat(depth) + l.replace(/\s*=\s*/g, " = ").replace(/\s+/g, " ");
    if (/[{([]\s*$/.test(l)) depth++;
    return out;
  }).join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
}
