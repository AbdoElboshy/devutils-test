export function kubectlBuild(action: string, o: { resource: string; name: string; namespace: string; extra: string; follow: boolean; output: string }): string {
  const ns = o.namespace && o.namespace !== "default" ? ` -n ${o.namespace}` : "";
  switch (action) {
    case "get": return `kubectl get ${o.resource || "pods"}${ns}${o.output ? ` -o ${o.output}` : ""}${o.extra ? ` ${o.extra}` : ""}`;
    case "describe": return `kubectl describe ${o.resource || "pod"} ${o.name || "<name>"}${ns}`;
    case "logs": return `kubectl logs ${o.name || "<pod>"}${ns}${o.follow ? " -f" : ""}${o.extra ? ` ${o.extra}` : ""}`;
    case "exec": return `kubectl exec -it ${o.name || "<pod>"}${ns} -- ${o.extra || "/bin/sh"}`;
    case "apply": return `kubectl apply -f ${o.extra || "deployment.yaml"}${ns}`;
    case "delete": return `kubectl delete ${o.resource || "pod"} ${o.name || "<name>"}${ns}`;
    case "port-forward": return `kubectl port-forward ${o.name || "svc/my-svc"}${ns} 8080:80`;
    case "top": return `kubectl top ${o.resource || "pods"}${ns}`;
    default: return `kubectl ${action} ${o.resource}${ns}`;
  }
}

