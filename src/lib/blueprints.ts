export function k8sConfigMap(o: K8sCommon & { data: string }): string {
  const lines = o.data.trim() ? o.data.split("\n").map((l) => l.trim()).filter(Boolean).map((l) => { const i = l.indexOf("="); if (i < 0) return `  ${l}: ""`; return `  ${l.slice(0, i).trim()}: ${JSON.stringify(l.slice(i + 1).trim())}`; }).join("\n") : '  key: "value"';
  return `apiVersion: v1\nkind: ConfigMap\n${kMeta(o)}\ndata:\n${lines}\n`;
}
export function k8sSecret(o: K8sCommon & { data: string }): string {
  const lines = o.data.trim() ? o.data.split("\n").map((l) => l.trim()).filter(Boolean).map((l) => { const i = l.indexOf("="); const k = i < 0 ? l : l.slice(0, i).trim(); const v = i < 0 ? "" : l.slice(i + 1).trim(); let bin = ""; try { const te = new TextEncoder(); const bytes = te.encode(v); bin = btoa(String.fromCharCode(...bytes)); } catch { bin = ""; } return `  ${k}: ${bin}`; }).join("\n") : "  password: cGFzc3dvcmQ=";
  return `apiVersion: v1\nkind: Secret\n${kMeta(o)}\ntype: Opaque\ndata:\n${lines}\n`;
}
