export type DockerRunOpts = {
  image: string; name: string; detach: boolean; rm: boolean; interactive: boolean; tty: boolean;
  ports: { host: string; container: string; proto: string }[];
  volumes: { host: string; container: string; ro: boolean }[];
  env: { k: string; v: string }[];
  network: string; restart: string; extra: string;
};
export function dockerRun(o: DockerRunOpts): string {
  const parts = ["docker run"];
  if (o.detach) parts.push("-d");
  if (o.rm) parts.push("--rm");
  if (o.interactive) parts.push("-i");
  if (o.tty) parts.push("-t");
  if (o.name.trim()) parts.push(`--name ${q(o.name.trim())}`);
  if (o.restart && o.restart !== "no") parts.push(`--restart ${o.restart}`);
  if (o.network.trim()) parts.push(`--network ${q(o.network.trim())}`);
  o.ports.filter((p) => p.host || p.container).forEach((p) => {
    const proto = p.proto && p.proto !== "tcp" ? `/${p.proto}` : "";
    parts.push(`-p ${q(`${p.host || "?"}:${p.container}${proto}`)}`);
  });
  o.volumes.filter((v) => v.host || v.container).forEach((v) => parts.push(`-v ${q(`${v.host}:${v.container}${v.ro ? ":ro" : ""}`)}`));
  o.env.filter((e) => e.k).forEach((e) => parts.push(`-e ${q(`${e.k}=${e.v}`)}`));
  if (o.extra.trim()) parts.push(o.extra.trim());
  parts.push(o.image.trim() || "nginx:alpine");
  return parts.join(" ");
}
function q(s: string) { return /[\s"'$`\\]/.test(s) ? `'${s.replace(/'/g, `'\\''`)}'` : s; }

export type DockerfileOpts = { base: string; workdir: string; copy: string; run: string; expose: string; env: { k: string; v: string }[]; cmd: string; multistage: boolean; nodeVersion: string };
export function dockerfileGen(o: DockerfileOpts): string {
  const L: string[] = [];
  if (o.multistage) {
    L.push(`FROM ${o.base || "node:20-alpine"} AS build`);
    L.push(`WORKDIR ${o.workdir || "/app"}`);
    if (o.copy) L.push(`COPY ${o.copy} ./`);
    if (o.run) o.run.split("\n").map((s) => s.trim()).filter(Boolean).forEach((r) => L.push(`RUN ${r}`));
    L.push("");
    L.push(`FROM ${o.base || "node:20-alpine"} AS runtime`);
    L.push(`WORKDIR ${o.workdir || "/app"}`);
    L.push(`COPY --from=build ${o.workdir || "/app"} ${o.workdir || "/app"}`);
  } else {
    L.push(`FROM ${o.base || "node:20-alpine"}`);
    L.push(`WORKDIR ${o.workdir || "/app"}`);
    if (o.copy) L.push(`COPY ${o.copy} ./`);
    if (o.run) o.run.split("\n").map((s) => s.trim()).filter(Boolean).forEach((r) => L.push(`RUN ${r}`));
  }
  o.env.filter((e) => e.k).forEach((e) => L.push(`ENV ${e.k}=${JSON.stringify(e.v)}`));
  if (o.expose.trim()) L.push(`EXPOSE ${o.expose.trim()}`);
  L.push(`CMD ${o.cmd.trim() || '["node", "index.js"]'}`);
  return L.join("\n") + "\n";
}

export type ComposeOpts = { project: string; services: { name: string; image: string; ports: string; volumes: string; env: string; restart: string }[] };
export function composeGen(o: ComposeOpts): string {
  const L = [`# ${o.project || "app"} — generated by DevUtils`, `services:`];
  (o.services.length ? o.services : [{ name: "web", image: "nginx:alpine", ports: "8080:80", volumes: "", env: "", restart: "unless-stopped" }]).forEach((s) => {
    L.push(`  ${s.name || "web"}:`);
    L.push(`    image: ${s.image || "nginx:alpine"}`);
    if (s.restart) L.push(`    restart: ${s.restart}`);
    if (s.ports.trim()) s.ports.split("\n").map((x) => x.trim()).filter(Boolean).forEach((p) => { if (!L.includes("    ports:")) L.push("    ports:"); L.push(`      - "${p}"`); });
    if (s.volumes.trim()) { L.push("    volumes:"); s.volumes.split("\n").map((x) => x.trim()).filter(Boolean).forEach((v) => L.push(`      - "${v}"`)); }
    if (s.env.trim()) { L.push("    environment:"); s.env.split("\n").map((x) => x.trim()).filter(Boolean).forEach((v) => L.push(`      - ${v}`)); }
  });
  return L.join("\n") + "\n";
}

