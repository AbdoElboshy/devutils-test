/* ================= LINUX BUILDERS ================= */

export function shQuote(s: string) { return /[^A-Za-z0-9_@%+=:,./-]/.test(s) ? `'${s.replace(/'/g, `'\\''`)}'` : s; }
export function buildGrep(o: { pattern: string; path: string; recursive: boolean; ignoreCase: boolean; lineNumbers: boolean; invert: boolean; count: boolean; fixed: boolean }): string {
  const f = ["grep"];
  if (o.recursive) f.push("-r");
  if (o.ignoreCase) f.push("-i");
  if (o.lineNumbers) f.push("-n");
  if (o.invert) f.push("-v");
  if (o.count) f.push("-c");
  if (o.fixed) f.push("-F");
  f.push(shQuote(o.pattern || "<pattern>"));
  if (o.path) f.push(shQuote(o.path));
  return f.join(" ");
}
export function buildFind(o: { path: string; name: string; type: string; newer: string; exec: string }): string {
  const f = ["find", shQuote(o.path || ".")];
  if (o.type) f.push("-type", o.type);
  if (o.name) f.push("-name", shQuote(o.name));
  if (o.newer) f.push("-newer", shQuote(o.newer));
  if (o.exec) f.push("-exec", o.exec, "{} +");
  return f.join(" ");
}
export function buildTar(o: { mode: string; archive: string; sources: string; gzip: boolean; verbose: boolean }): string {
  const flags = o.mode === "create" ? `c${o.gzip ? "z" : ""}${o.verbose ? "v" : ""}f` : o.mode === "extract" ? `x${o.gzip ? "z" : ""}${o.verbose ? "v" : ""}f` : `t${o.gzip ? "z" : ""}${o.verbose ? "v" : ""}f`;
  return `tar -${flags} ${shQuote(o.archive || "archive.tar.gz")} ${o.sources || "<files>"}`;
}
export function buildRsync(o: { src: string; dest: string; archive: boolean; compress: boolean; delete: boolean; dry: boolean; exclude: string; verbose?: boolean }): string {
  const f = ["rsync"];
  if (o.archive) f.push("-a");
  if (o.compress) f.push("-z");
  if (o.verbose !== false) f.push("-v");
  f.push("--progress");
  if (o.delete) f.push("--delete");
  if (o.dry) f.push("--dry-run");
  if (o.exclude.trim()) o.exclude.split("\n").map((s) => s.trim()).filter(Boolean).forEach((e) => f.push(`--exclude=${shQuote(e)}`));
  f.push(shQuote(o.src || "src/"), shQuote(o.dest || "dest/"));
  return f.join(" ");
}
export function buildSsh(o: { user: string; host: string; port: string; key: string; forward: string; extra: string }): string {
  const f = ["ssh"];
  if (o.port && o.port !== "22") f.push("-p", o.port);
  if (o.key) f.push("-i", shQuote(o.key));
  if (o.forward) f.push("-L", o.forward);
  if (o.extra) f.push(o.extra);
  f.push(`${o.user ? o.user + "@" : ""}${o.host || "<host>"}`);
  return f.join(" ");
}
export function buildScp(o: { src: string; dest: string; port: string; key: string; recursive: boolean }): string {
  const f = ["scp"];
  if (o.port && o.port !== "22") f.push("-P", o.port);
  if (o.key) f.push("-i", shQuote(o.key));
  if (o.recursive) f.push("-r");
  f.push(shQuote(o.src || "file"), shQuote(o.dest || "user@host:/path"));
  return f.join(" ");
}
