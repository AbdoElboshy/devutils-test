export function cspBuild(o: { defaultSrc: string; script: string; style: string; img: string; connect: string; frame: string; extra: string }): string {
  const parts = [`default-src ${o.defaultSrc || "'self'"}`, `script-src ${o.script || "'self'"}`, `style-src ${o.style || "'self'"}`, `img-src ${o.img || "'self' data:"}`, `connect-src ${o.connect || "'self'"}`, `frame-ancestors ${o.frame || "'none'"}`];
  if (o.extra.trim()) parts.push(o.extra.trim().replace(/;$/, ""));
  return parts.join("; ") + ";";
}
export function robotsBuild(o: { allow: string; disallow: string; sitemap: string }): string {
  const L = ["User-agent: *"];
  o.allow.split("\n").map((s) => s.trim()).filter(Boolean).forEach((s) => L.push(`Allow: ${s}`));
  o.disallow.split("\n").map((s) => s.trim()).filter(Boolean).forEach((s) => L.push(`Disallow: ${s}`));
  if (o.sitemap.trim()) L.push(`Sitemap: ${o.sitemap.trim()}`);
  return L.join("\n") + "\n";
}
