export type K8sCommon = { name: string; namespace: string; labels: string; image: string; replicas: number; port: number };
function kMeta(o: K8sCommon, extra = ""): string {
  const labels = o.labels.trim() ? `\n    ${o.labels.trim().split("\n").map((l) => l.trim()).filter(Boolean).join("\n    ")}` : `\n    app: ${o.name || "app"}`;
  return `metadata:\n  name: ${o.name || "app"}${o.namespace.trim() && o.namespace !== "default" ? `\n  namespace: ${o.namespace.trim()}` : ""}\n  labels:${labels}${extra}`;
}
export function k8sDeployment(o: K8sCommon & { cpu: string; memory: string; cpuLimit?: string; memoryLimit?: string; env: string }): string {
  const envLines = o.env.trim() ? `\n        env:\n${o.env.split("\n").map((l) => l.trim()).filter(Boolean).map((l) => { const [k, ...rest] = l.split("="); return `        - name: ${k.trim()}\n          value: ${JSON.stringify(rest.join("=").trim())}`; }).join("\n")}` : "";
  const res = o.cpu || o.memory || o.cpuLimit || o.memoryLimit ? `\n        resources:${o.cpu || o.memory ? `\n          requests:\n${o.cpu ? `            cpu: ${o.cpu}\n` : ""}${o.memory ? `            memory: ${o.memory}` : ""}` : ""}${o.cpuLimit || o.memoryLimit ? `\n          limits:\n${o.cpuLimit ? `            cpu: ${o.cpuLimit}\n` : ""}${o.memoryLimit ? `            memory: ${o.memoryLimit}` : ""}` : ""}`.replace(/\n$/, "") : "";
  return `apiVersion: apps/v1\nkind: Deployment\n${kMeta(o)}\nspec:\n  replicas: ${o.replicas}\n  selector:\n    matchLabels:\n      app: ${o.name || "app"}\n  template:\n    metadata:\n      labels:\n        app: ${o.name || "app"}\n    spec:\n      containers:\n      - name: ${o.name || "app"}\n        image: ${o.image || "nginx:alpine"}\n        ports:\n        - containerPort: ${o.port || 80}${envLines}${res}\n`;
}
