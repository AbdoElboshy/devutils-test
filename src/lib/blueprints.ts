export type HttpReq = { method: string; url: string; headers: { k: string; v: string }[]; auth: string; body: string; contentType: string };
export function parseCurl(cmd: string): HttpReq {
  const t = cmd.trim();
  if (!/curl/i.test(t)) throw new Error('Paste a curl command starting with "curl".');
  // tokenize respecting quotes
  const tokens: string[] = [];
  let cur = "", quote = "", esc = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (esc) { cur += c; esc = false; continue; }
    if (c === "\\" && quote !== "'") { esc = true; continue; }
    if (quote) { if (c === quote) { quote = ""; } else cur += c; continue; }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (/\s/.test(c)) { if (cur) { tokens.push(cur); cur = ""; } continue; }
    cur += c;
  }
  if (cur) tokens.push(cur);
  const req: HttpReq = { method: "GET", url: "", headers: [], auth: "", body: "", contentType: "" };
  let explicitMethod = false;
  for (let i = 0; i < tokens.length; i++) {
    const tok = tokens[i];
    if (tok === "curl") continue;
    if (tok === "-X" || tok === "--request") { req.method = (tokens[++i] || "GET").toUpperCase(); explicitMethod = true; }
    else if (tok === "-H" || tok === "--header") {
      const h = tokens[++i] || "";
      const idx = h.indexOf(":");
      if (idx > 0) {
        const k = h.slice(0, idx).trim(), v = h.slice(idx + 1).trim();
        if (/^authorization$/i.test(k)) req.auth = v.replace(/^Bearer\s+/i, "");
        else req.headers.push({ k, v });
        if (/^content-type$/i.test(k)) req.contentType = v;
      }
    }
    else if (tok === "-u" || tok === "--user") req.auth = `Basic ${tokens[++i] || ""}`;
    else if (["-d", "--data", "--data-raw", "--data-binary", "--data-ascii"].includes(tok)) { req.body = tokens[++i] ?? ""; if (!explicitMethod) req.method = "POST"; }
    else if (tok === "--json") { req.body = tokens[++i] ?? ""; req.contentType = "application/json"; if (!explicitMethod) req.method = "POST"; }
    else if (tok.startsWith("-")) { if (!tokens[i + 1] || tokens[i + 1].startsWith("-")) continue; i++; }
    else if (!req.url && /^https?:\/\//.test(tok)) req.url = tok;
    else if (!req.url && tok.includes(".") && !tok.startsWith("-")) req.url = tok.startsWith("http") ? tok : `https://${tok}`;
  }
  if (!req.url) throw new Error("No URL found in the curl command.");
  return req;
}
export function buildCurl(r: HttpReq): string {
  const parts = [`curl -X ${r.method || "GET"} ${q(r.url)}`];
  if (r.auth.startsWith("Basic ")) parts.push(`-u ${q(r.auth.slice(6))}`);
  effectiveHeaders(r).forEach((h) => { if (h.k) parts.push(`-H ${q(`${h.k}: ${h.v}`)}`); });
  if (r.body) {
    parts.push(`--data-raw ${q(r.body)}`);
  }
  return parts.join(" \\\n  ");
}
export function effectiveHeaders(r: HttpReq): { k: string; v: string }[] {
  const h = [...r.headers];
  if (r.contentType && !h.some((x) => x.k.toLowerCase() === "content-type")) h.push({ k: "Content-Type", v: r.contentType });
  if (r.auth && !r.auth.startsWith("Basic ")) h.push({ k: "Authorization", v: `Bearer ${r.auth}` });
  return h;
}
